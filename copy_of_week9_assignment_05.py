def stock_status(stock):
    """Return 'OUT' if stock is 0, 'LOW' if stock is less than 5, otherwise 'OK'."""
    if stock == 0:
        return 'OUT'
    elif stock < 5:
        return 'LOW'
    else:
        return 'OK'


def best_seller(sold):
    """Return the code of the product with the highest total quantity sold."""
    if not sold or max(sold.values()) == 0:
        return None
    return max(sold, key=sold.get)


def save_stock(filename, products):
    """Write the updated products to filename, in the same format as products.csv."""
    with open(filename, 'w') as f:
        for code, data in products.items():
            f.write(f"{code},{data['name']},{data['price']},{data['stock']}\n")


def process_sales(products_filename, sales_filename):
    products = {}
    with open(products_filename, 'r') as f:
        for line in f:
            line = line.strip()
            if line:
                parts = line.split(',')
                code = parts[0].strip().upper()
                name = parts[1].strip()
                price = float(parts[2])
                stock = int(parts[3])
                products[code] = {'name': name, 'price': price, 'stock': stock}

    sold = {code: 0 for code in products}
    revenue = {code: 0.0 for code in products}
    errors = []

    with open(sales_filename, 'r') as f:
        lines = f.readlines()

    for idx, line in enumerate(lines, start=1):
        line = line.strip()
        if not line:
            continue
        parts = line.split(',')
        if len(parts) != 2:
            continue
        code_raw = parts[0].strip().upper()
        qty_raw = parts[1].strip()

        # Check if quantity is a valid whole number
        if not qty_raw.isdigit():
            errors.append(f"Line {idx}: '{qty_raw}' is not a valid quantity")
            continue

        qty = int(qty_raw)

        # Check if product code exists
        if code_raw not in products:
            errors.append(f"Line {idx}: unknown product code {code_raw}")
            continue

        prod = products[code_raw]

        # Check if enough stock
        if qty > prod['stock']:
            errors.append(f"Line {idx}: not enough stock for {code_raw} (wanted {qty}, have {prod['stock']})")
            continue

        # Valid sale
        prod['stock'] -= qty
        line_money = prod['price'] * qty
        if qty >= 10:
            line_money *= 0.90  # 10% discount for quantity >= 10

        sold[code_raw] += qty
        revenue[code_raw] += line_money

    return products, sold, revenue, errors


